Set-StrictMode -Version Latest

<#
    Column descriptions: a JSON file in the schema project is the source; a generated SQL file
    turns every entry into an MS_Description extended property, so the descriptions are part of
    the dacpac model and deploy (and drift-correct) like any other schema object.

    The JSON file:
      standardColumns  description proposed for columns that every table has (CreatedAt, ...)
      excludedTables   tables that need no descriptions ('Schema.Table')
      tables           'Schema.Table' -> { description, columns: { name -> description } }
#>

$script:DescriptionsSqlHeader = @(
    '-- <auto-generated>'
    '-- Generated by scripts/Update-ColumnDescriptions.ps1 from ColumnDescriptions.json.'
    '-- Do not edit: CI regenerates this file and fails when it differs.'
    '-- </auto-generated>'
)

function Read-ColumnDescription {
    <# Reads and checks the shape of a column descriptions file. #>
    param([Parameter(Mandatory)] [string] $Path)

    $descriptions = Read-JsonFile -Path $Path
    if ($descriptions -isnot [System.Collections.IDictionary]) {
        throw "${Path}: the root must be an object."
    }
    foreach ($key in @('standardColumns', 'excludedTables', 'tables')) {
        if (-not $descriptions.Contains($key)) {
            throw "${Path}: missing '$key'."
        }
    }
    foreach ($tableName in @($descriptions.tables.Keys)) {
        if ($tableName -notmatch '^[^.]+\.[^.]+$') {
            throw "${Path}: table '$tableName' must be written as Schema.Table."
        }
        $table = $descriptions.tables[$tableName]
        if ($table -isnot [System.Collections.IDictionary] -or -not $table.Contains('columns') -or $table.columns -isnot [System.Collections.IDictionary]) {
            throw "${Path}: table '$tableName' must have a 'columns' object."
        }
    }
    $descriptions
}

function ConvertTo-WordPhrase {
    <# 'ProductCategory' -> 'product category'. #>
    param([Parameter(Mandatory)] [string] $Name)
    ([regex]::Replace($Name, '(?<=[a-z0-9])(?=[A-Z])', ' ')).ToLowerInvariant()
}

function Get-ColumnDescriptionProposal {
    <# A starting description for a new column, or '' when only a human can write one. #>
    param(
        [Parameter(Mandatory)] [object] $Table,
        [Parameter(Mandatory)] [object] $Column,
        [Parameter(Mandatory)] [System.Collections.IDictionary] $StandardColumns
    )
    if ($StandardColumns.Contains($Column.Name)) {
        return [string]$StandardColumns[$Column.Name]
    }
    if ($Column.IsPrimaryKey) {
        return "Unique identifier of the $(ConvertTo-WordPhrase -Name $Table.Table)."
    }
    if ($Column.ReferencedTable) {
        return "Reference to $($Column.ReferencedTable)."
    }
    ''
}

function Compare-ColumnDescription {
    <#
    .SYNOPSIS
        Compares the descriptions file with the tables of the built model.
    .DESCRIPTION
        Emits one finding per problem: Kind (MissingTable, MissingColumn, ObsoleteTable,
        ObsoleteColumn, EmptyDescription, UnknownExcludedTable), Table, Column and Message.
    #>
    param(
        [Parameter(Mandatory)] [System.Collections.IDictionary] $Descriptions,
        [Parameter(Mandatory)] [AllowEmptyCollection()] [object[]] $Tables
    )

    $excluded = [System.Collections.Generic.HashSet[string]]::new([string[]]@($Descriptions.excludedTables), [System.StringComparer]::OrdinalIgnoreCase)
    $modelTables = @{}
    foreach ($table in $Tables) {
        $modelTables[$table.Name.ToLowerInvariant()] = $table
    }

    foreach ($name in @($excluded)) {
        if (-not $modelTables.ContainsKey($name.ToLowerInvariant())) {
            [pscustomobject]@{ Kind = 'UnknownExcludedTable'; Table = $name; Column = $null; Message = "excludedTables lists $name, which is not in the model." }
        }
    }

    foreach ($table in $Tables) {
        if ($excluded.Contains($table.Name)) {
            continue
        }
        $entry = $null
        foreach ($key in @($Descriptions.tables.Keys)) {
            if ($key -ieq $table.Name) { $entry = $Descriptions.tables[$key] }
        }
        if ($null -eq $entry) {
            [pscustomobject]@{ Kind = 'MissingTable'; Table = $table.Name; Column = $null; Message = "$($table.Name) has no descriptions." }
            continue
        }
        if (-not $entry.Contains('description') -or [string]::IsNullOrWhiteSpace([string]$entry.description)) {
            [pscustomobject]@{ Kind = 'EmptyDescription'; Table = $table.Name; Column = $null; Message = "$($table.Name) has no table description." }
        }
        $modelColumns = [System.Collections.Generic.HashSet[string]]::new([string[]]@($table.Columns | ForEach-Object Name), [System.StringComparer]::OrdinalIgnoreCase)
        foreach ($column in $table.Columns) {
            $described = @($entry.columns.Keys | Where-Object { $_ -ieq $column.Name })
            if ($described.Count -eq 0) {
                [pscustomobject]@{ Kind = 'MissingColumn'; Table = $table.Name; Column = $column.Name; Message = "$($table.Name).$($column.Name) has no description." }
            }
            elseif ([string]::IsNullOrWhiteSpace([string]$entry.columns[$described[0]])) {
                [pscustomobject]@{ Kind = 'EmptyDescription'; Table = $table.Name; Column = $column.Name; Message = "$($table.Name).$($column.Name) has an empty description." }
            }
        }
        foreach ($columnName in @($entry.columns.Keys)) {
            if (-not $modelColumns.Contains($columnName)) {
                [pscustomobject]@{ Kind = 'ObsoleteColumn'; Table = $table.Name; Column = $columnName; Message = "$($table.Name).$columnName is described but not in the model." }
            }
        }
    }

    foreach ($key in @($Descriptions.tables.Keys)) {
        if (-not $modelTables.ContainsKey($key.ToLowerInvariant())) {
            [pscustomobject]@{ Kind = 'ObsoleteTable'; Table = $key; Column = $null; Message = "$key is described but not in the model." }
        }
        elseif ($excluded.Contains($key)) {
            [pscustomobject]@{ Kind = 'ObsoleteTable'; Table = $key; Column = $null; Message = "$key is both excluded and described." }
        }
    }
}

function Sync-ColumnDescription {
    <#
    .SYNOPSIS
        Returns a copy of the descriptions that matches the model: missing tables and columns are
        added with a proposal (or ''), obsolete ones are removed, and everything is sorted.
    #>
    param(
        [Parameter(Mandatory)] [System.Collections.IDictionary] $Descriptions,
        [Parameter(Mandatory)] [AllowEmptyCollection()] [object[]] $Tables
    )

    $excluded = [System.Collections.Generic.HashSet[string]]::new([string[]]@($Descriptions.excludedTables), [System.StringComparer]::OrdinalIgnoreCase)
    $result = [ordered]@{}
    if ($Descriptions.Contains('$schema')) {
        $result['$schema'] = $Descriptions['$schema']
    }
    $result.standardColumns = $Descriptions.standardColumns
    [string[]] $excludedNames = @($Descriptions.excludedTables | Where-Object { $name = $_; @($Tables | Where-Object { $_.Name -ieq $name }).Count -gt 0 })
    [System.Array]::Sort($excludedNames, [System.StringComparer]::Ordinal)
    $result.excludedTables = $excludedNames

    $resultTables = [ordered]@{}
    [string[]] $tableNames = @($Tables | Where-Object { -not $excluded.Contains($_.Name) } | ForEach-Object Name)
    [System.Array]::Sort($tableNames, [System.StringComparer]::Ordinal)
    foreach ($tableName in $tableNames) {
        $table = @($Tables | Where-Object Name -eq $tableName)[0]
        $existing = $null
        foreach ($key in @($Descriptions.tables.Keys)) {
            if ($key -ieq $tableName) { $existing = $Descriptions.tables[$key] }
        }
        $description = ''
        if ($null -ne $existing -and $existing.Contains('description')) {
            $description = [string]$existing.description
        }
        $columns = [ordered]@{}
        [string[]] $columnNames = @($table.Columns | ForEach-Object Name)
        [System.Array]::Sort($columnNames, [System.StringComparer]::Ordinal)
        foreach ($columnName in $columnNames) {
            $column = @($table.Columns | Where-Object Name -eq $columnName)[0]
            $value = $null
            if ($null -ne $existing) {
                foreach ($key in @($existing.columns.Keys)) {
                    if ($key -ieq $columnName) { $value = [string]$existing.columns[$key] }
                }
            }
            if ($null -eq $value) {
                $value = Get-ColumnDescriptionProposal -Table $table -Column $column -StandardColumns $Descriptions.standardColumns
            }
            $columns[$columnName] = $value
        }
        $resultTables[$tableName] = [ordered]@{ description = $description; columns = $columns }
    }
    $result.tables = $resultTables
    $result
}

function ConvertTo-ColumnDescriptionJson {
    param([Parameter(Mandatory)] [System.Collections.IDictionary] $Descriptions)
    (ConvertTo-Json -InputObject $Descriptions -Depth 10) + "`n"
}

function ConvertTo-SqlLiteral {
    param([Parameter(Mandatory)] [AllowEmptyString()] [string] $Value)
    "N'" + $Value.Replace("'", "''") + "'"
}

function ConvertTo-ColumnDescriptionSql {
    <#
    .SYNOPSIS
        One sp_addextendedproperty statement per table and column, sorted, separated by GO.
    .DESCRIPTION
        Built as part of the schema project, these statements become extended property elements
        of the model. Empty descriptions are skipped; the check reports them.
    #>
    param([Parameter(Mandatory)] [System.Collections.IDictionary] $Descriptions)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.AddRange([string[]]$script:DescriptionsSqlHeader)
    [string[]] $tableNames = @($Descriptions.tables.Keys)
    [System.Array]::Sort($tableNames, [System.StringComparer]::Ordinal)
    foreach ($tableName in $tableNames) {
        $schema, $table = $tableName.Split('.', 2)
        $entry = $Descriptions.tables[$tableName]
        $target = "@level0type = N'SCHEMA', @level0name = $(ConvertTo-SqlLiteral $schema), @level1type = N'TABLE', @level1name = $(ConvertTo-SqlLiteral $table)"
        if ($entry.Contains('description') -and -not [string]::IsNullOrWhiteSpace([string]$entry.description)) {
            $lines.Add("EXECUTE sp_addextendedproperty @name = N'MS_Description', @value = $(ConvertTo-SqlLiteral ([string]$entry.description)), $target;")
            $lines.Add('GO')
        }
        [string[]] $columnNames = @($entry.columns.Keys)
        [System.Array]::Sort($columnNames, [System.StringComparer]::Ordinal)
        foreach ($columnName in $columnNames) {
            $value = [string]$entry.columns[$columnName]
            if ([string]::IsNullOrWhiteSpace($value)) {
                continue
            }
            $lines.Add("EXECUTE sp_addextendedproperty @name = N'MS_Description', @value = $(ConvertTo-SqlLiteral $value), $target, @level2type = N'COLUMN', @level2name = $(ConvertTo-SqlLiteral $columnName);")
            $lines.Add('GO')
        }
    }
    ($lines -join "`n") + "`n"
}
