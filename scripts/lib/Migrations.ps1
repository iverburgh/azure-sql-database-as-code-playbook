Set-StrictMode -Version Latest

<#
    Registered migrations and the two generated runner scripts.

    A migration is a folder Migrations/NNNN_Description containing one or more .sql files. The
    folder is the registration: the number is the migration id, the files run in ordinal order.
    New-RunMigrationsSql and New-InitMigrationsSql turn the folders into the scripts that the
    hand-written post-deployment script includes. Both are deterministic, so CI can regenerate
    them and fail when the committed copy differs.
#>

$script:MigrationFolderPattern = '^(?<id>\d{4})_(?<name>[A-Za-z][A-Za-z0-9]*)$'
$script:GeneratedHeader = @(
    '-- <auto-generated>'
    '-- Generated by scripts/New-MigrationScripts.ps1 from the folders in Migrations.'
    '-- Do not edit: CI regenerates this file and fails when it differs.'
    '-- </auto-generated>'
)

function Get-Migration {
    <#
    .SYNOPSIS
        Emits the registered migrations of a migrations project, ordered by id.
    .PARAMETER ProjectPath
        The folder of the migrations project (the one that contains the Migrations folder).
    #>
    param([Parameter(Mandatory)] [string] $ProjectPath)

    $migrationsPath = Join-Path $ProjectPath 'Migrations'
    if (-not (Test-Path -LiteralPath $migrationsPath -PathType Container)) {
        return
    }

    $migrations = [System.Collections.Generic.List[object]]::new()
    foreach ($folder in @(Get-ChildItem -LiteralPath $migrationsPath -Directory)) {
        $match = [regex]::Match($folder.Name, $script:MigrationFolderPattern)
        if (-not $match.Success) {
            throw "Migration folder '$($folder.Name)' does not match NNNN_Description (four digits, an underscore, letters and digits)."
        }
        [string[]] $scripts = @(Get-ChildItem -LiteralPath $folder.FullName -File -Filter '*.sql' | ForEach-Object Name)
        [System.Array]::Sort($scripts, [System.StringComparer]::Ordinal)
        if ($scripts.Count -eq 0) {
            throw "Migration folder '$($folder.Name)' contains no .sql files."
        }
        $migrations.Add([pscustomobject]@{
                Id      = [int]$match.Groups['id'].Value
                Name    = $folder.Name
                Path    = $folder.FullName
                Scripts = $scripts
            })
    }

    $duplicates = @($migrations | Group-Object Id | Where-Object Count -gt 1)
    if ($duplicates.Count -gt 0) {
        $names = @($duplicates | ForEach-Object { @($_.Group | ForEach-Object Name) -join ', ' }) -join '; '
        throw "Two migrations share an id: $names. Renumber the newest one."
    }
    if (@($migrations | Where-Object Id -eq 0).Count -gt 0) {
        throw 'Migration id 0000 is not allowed; start at 0001.'
    }

    foreach ($migration in @($migrations | Sort-Object Id)) {
        $migration
    }
}

function Remove-SqlComment {
    <# Removes -- and /* */ comments and the contents of string literals, so rules only see code. #>
    param([Parameter(Mandatory)] [AllowEmptyString()] [string] $Sql)
    $pattern = "(?s)/\*.*?\*/|--[^\r\n]*|N?'(?:[^']|'')*'"
    [regex]::Replace($Sql, $pattern, {
            param($m)
            if ($m.Value.EndsWith("'")) { return "''" }
            if ($m.Value.StartsWith('/*')) { return ' ' }
            return ''
        })
}

function Test-MigrationScript {
    <#
    .SYNOPSIS
        Emits one message per rule violation in the given migrations; emits nothing when they are fine.
    .DESCRIPTION
        All migrations run inside one transaction in one batch, so:
        - no GO (it would split the batch and break the IF block around the migration),
        - no USE, no transaction statements and no SQLCMD commands,
        - no sp_cdc_enable_table or sp_cdc_disable_table (change data capture is reconciled from
          its own desired state, never from a migration),
        - a variable can be declared by only one migration.
    #>
    param([Parameter(Mandatory)] [AllowEmptyCollection()] [object[]] $Migrations)

    $declaredBy = @{}
    foreach ($migration in $Migrations) {
        foreach ($scriptName in $migration.Scripts) {
            $location = "$($migration.Name)/$scriptName"
            $raw = [System.IO.File]::ReadAllText((Join-Path $migration.Path $scriptName))
            $code = Remove-SqlComment -Sql $raw

            if ($raw -match '(?im)^\s*GO\s*(--.*)?$') {
                "${location}: contains GO. Migrations run in one batch; use sp_executesql instead."
            }
            if ($raw -match '(?im)^\s*:[a-z]+') {
                "${location}: contains a SQLCMD command (such as :r or :setvar). Put the SQL in the migration folder instead."
            }
            if ($code -match '(?im)^\s*USE\s') {
                "${location}: contains USE. A migration always runs in the database it is deployed to."
            }
            if ($code -match '(?i)\b(BEGIN\s+(TRAN|TRANSACTION|DISTRIBUTED)\b|COMMIT\b|ROLLBACK\b|SAVE\s+(TRAN|TRANSACTION)\b)') {
                "${location}: contains a transaction statement. The runner wraps all migrations in one transaction."
            }
            if ($code -match '(?i)\bsp_cdc_(enable|disable)_(table|db)\b') {
                "${location}: enables or disables change data capture. Change the captured columns through their owner instead; see docs/cdc-and-schema-changes.md."
            }
            foreach ($declaration in [regex]::Matches($code, '(?i)\bDECLARE\s+(@[A-Za-z0-9_#$@]+)')) {
                $variable = $declaration.Groups[1].Value.ToLowerInvariant()
                if ($declaredBy.ContainsKey($variable) -and $declaredBy[$variable] -ne $migration.Name) {
                    "${location}: declares $($declaration.Groups[1].Value), which $($declaredBy[$variable]) declares too. All migrations share one batch; use a unique name."
                }
                elseif (-not $declaredBy.ContainsKey($variable)) {
                    $declaredBy[$variable] = $migration.Name
                }
            }
        }
    }
}

function New-RunMigrationsSql {
    <# The script that runs each migration once, on a database that already has dbo.DeploymentHistory. #>
    param([Parameter(Mandatory)] [AllowEmptyCollection()] [object[]] $Migrations)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.AddRange([string[]]$script:GeneratedHeader)
    if ($Migrations.Count -eq 0) {
        $lines.Add("PRINT N'No migrations registered.';")
        return ($lines -join "`n") + "`n"
    }

    $first = $true
    foreach ($migration in $Migrations) {
        if (-not $first) {
            $lines.Add('')
        }
        $first = $false
        $lines.Add("IF NOT EXISTS (SELECT 1 FROM [dbo].[DeploymentHistory] WHERE [MigrationId] = $($migration.Id))")
        $lines.Add('BEGIN')
        $lines.Add("    PRINT N'Running migration $($migration.Name).';")
        foreach ($scriptName in $migration.Scripts) {
            # SQLCMD resolves :r relative to the including file; forward slashes work on every platform.
            $lines.Add(":r ../../Migrations/$($migration.Name)/$scriptName")
        }
        $lines.Add('    INSERT INTO [dbo].[DeploymentHistory] ([Type], [Build], [MigrationId], [Name])')
        $lines.Add("    VALUES (N'Migration', N'`$(BuildNumber)', $($migration.Id), N'$($migration.Name)');")
        $lines.Add('END')
    }
    ($lines -join "`n") + "`n"
}

function New-InitMigrationsSql {
    <# The script that records every migration as already applied, on a new database. #>
    param([Parameter(Mandatory)] [AllowEmptyCollection()] [object[]] $Migrations)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.AddRange([string[]]$script:GeneratedHeader)
    if ($Migrations.Count -eq 0) {
        $lines.Add("PRINT N'No migrations registered.';")
        return ($lines -join "`n") + "`n"
    }

    $lines.Add('INSERT INTO [dbo].[DeploymentHistory] ([Type], [Build], [MigrationId], [Name])')
    $lines.Add('VALUES')
    for ($index = 0; $index -lt $Migrations.Count; $index++) {
        $migration = $Migrations[$index]
        $separator = if ($index -eq $Migrations.Count - 1) { ';' } else { ',' }
        $lines.Add("    (N'Baseline', N'`$(BuildNumber)', $($migration.Id), N'$($migration.Name)')$separator")
    }
    ($lines -join "`n") + "`n"
}
