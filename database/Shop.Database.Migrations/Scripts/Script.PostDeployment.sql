/*
Runs every registered migration that has not run on this database yet, in one transaction.

- A database without dbo.DeploymentHistory is new: the schema dacpac creates every table in its
  final shape, so there is nothing to migrate. The table is created and every migration is
  recorded as a baseline.
- Otherwise each migration runs once and is recorded in dbo.DeploymentHistory.

The two included files are generated by scripts/New-MigrationScripts.ps1. Do not edit them.
All migrations end up in a single batch: no GO, and use sp_executesql for statements that refer
to columns or tables that may not exist when the batch is compiled.
*/
SET XACT_ABORT ON;
SET NOCOUNT ON;

BEGIN TRANSACTION;

IF OBJECT_ID(N'[dbo].[DeploymentHistory]', N'U') IS NULL
BEGIN
    PRINT N'New database: recording every migration as a baseline.';
:r ../../Shop.Database/dbo/Tables/DeploymentHistory.sql
:r ./Generated/InitMigrations.sql
END
ELSE
BEGIN
:r ./Generated/RunMigrations.sql
END

COMMIT TRANSACTION;
